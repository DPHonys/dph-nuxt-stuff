import type { Nitro } from 'nitropack/types'
// PROTOTYPE (ticket 10). The generated map, emitted the way the spec says:
// Nitro's scanned handlers, re-emitted on `types:extend`. One template, both
// slots (`KnownApiRequestInputs`, `KnownApiErrors`).
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { addTypeTemplate, defineNuxtModule, updateTemplates } from 'nuxt/kit'

const FILENAME = 'types/better-map.d.ts'
const LIB = fileURLToPath(new URL('../lib/', import.meta.url))

function specifier(from: string, to: string): string {
  const path = relative(from, to)
    .replaceAll('\\', '/')
    .replace(/\.[cm]?[jt]s$/, '')
  return path.startsWith('.') ? path : `./${path}`
}

interface Entry {
  route: string
  method: string
  handler: string
}

function render(typesDir: string, entries: readonly Entry[]): string {
  const byRoute = new Map<string, Map<string, string[]>>()
  for (const { route, method, handler } of entries) {
    const methods = byRoute.get(route) ?? new Map<string, string[]>()
    const handlers = methods.get(method) ?? []
    const type = `typeof import('${specifier(typesDir, handler)}').default`
    if (!handlers.includes(type)) handlers.push(type)
    methods.set(method, handlers)
    byRoute.set(route, methods)
  }
  const routes = [...byRoute].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  const slot = (name: string, wrap: (h: string) => string): string =>
    [
      `  interface ${name} {`,
      ...routes.map(([route, methods]) =>
        [
          `    '${route}': {`,
          ...[...methods].map(
            ([method, handlers]) =>
              `      '${method}': ${handlers.map(wrap).join(' | ')}`
          ),
          '    }',
        ].join('\n')
      ),
      '  }',
    ].join('\n')
  const lib = (file: string) => specifier(typesDir, join(LIB, file))
  return [
    '// GENERATED by prototypes/10-native-slot/module/better-map.ts',
    `import type { Wire, WireInput } from '${lib('engine')}'`,
    `import type { KnownErrorsOfHandler, RequestInputOfHandler } from '${lib('handler')}'`,
    '',
    `declare module '${lib('request-typing')}' {`,
    slot(
      'KnownApiRequestInputs',
      (h) => `WireInput<RequestInputOfHandler<${h}>>`
    ),
    slot('KnownApiErrors', (h) => `Wire<KnownErrorsOfHandler<${h}>>`),
    '}',
    '',
    'export {}',
    '',
  ].join('\n')
}

export default defineNuxtModule({
  meta: { name: 'better-map' },
  setup(_options, nuxt) {
    let nitro: Nitro | undefined
    const typesDir = join(nuxt.options.buildDir, 'types')

    addTypeTemplate(
      {
        filename: FILENAME,
        getContents: () =>
          render(
            typesDir,
            nitro === undefined
              ? []
              : [...nitro.scannedHandlers, ...nitro.options.handlers]
                  .filter((h) => !h.middleware && h.route && h.handler)
                  .map((h) => ({
                    route: h.route!,
                    method: h.method ? h.method.toLowerCase() : 'default',
                    handler: h.handler,
                  }))
          ),
      },
      { nitro: true, nuxt: true, shared: true }
    )

    nuxt.hook('nitro:init', (instance) => {
      nitro = instance
      instance.hooks.hook('types:extend', async () => {
        await updateTemplates({ filter: (t) => t.filename === FILENAME })
      })
    })
  },
})
