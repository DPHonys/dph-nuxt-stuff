// PROTOTYPE: writes generated/map.d.ts — what the generalised emitMap would emit, plus 45
// synthetic routes so the stack-depth rule (~50-entry map, no TS2321) is exercised.
import { writeFileSync } from 'node:fs'
const real = [
  ['/api/users', 'post', '../routes/users.post'],
  ['/api/users', 'get', '../routes/users.get'],
  ['/api/items/:id', 'default', '../routes/items-id'],
  ['/api/plain', 'get', '../routes/plain.get'],
  ['/api/errors-only', 'post', '../routes/errors-only.post'],
  ['/api/params-only/:slug', 'post', '../routes/params-only.post'],
  // two handlers on one (route, method) → union
  ['/api/multi', 'post', '../routes/users.post'],
  ['/api/multi', 'post', '../routes/items-id'],
]
const byRoute = {}
for (const [r, m, s] of real) ((byRoute[r] ??= {})[m] ??= []).push(s)
for (let i = 0; i < 45; i++) {
  const r = `/api/gen/${i}/:id`
  byRoute[r] = { get: [i % 2 ? '../routes/users.get' : '../routes/plain.get'], post: ['../routes/users.post'] }
}
const H = (s) => `typeof import('${s}').default`
const block = (name, val) =>
  `  interface ${name} {\n` +
  Object.entries(byRoute)
    .map(([r, ms]) => `    '${r}': {\n` + Object.entries(ms).map(([m, hs]) => `      '${m}': ${hs.map(val).join(' | ')}`).join('\n') + '\n    }')
    .join('\n') +
  '\n  }\n'
const out =
  `// GENERATED BY gen-map.mjs — PROTOTYPE\nimport type { Simplify, Serialize } from 'nitropack/types'\nimport type { KnownErrorsOfHandler } from '../../src/runtime/types'\nimport type { RequestInputOfHandler } from '../lib/validation-types'\n\n` +
  `declare module 'nitropack/types' {\n${block('InternalApi', (h) => `Simplify<Serialize<Awaited<ReturnType<${H(h)}>>>>`)}}\n\n` +
  `declare module '../../src/runtime/types' {\n${block('KnownApiErrors', (h) => `Simplify<Serialize<KnownErrorsOfHandler<${H(h)}>>>`)}}\n\n` +
  `declare module '../lib/typed-fetch' {\n${block('KnownApiRequestInputs', (h) => `Simplify<RequestInputOfHandler<${H(h)}>>`)}}\n`
writeFileSync(new URL('./generated/map.d.ts', import.meta.url), out)
console.log(`wrote ${Object.keys(byRoute).length} routes`)
