/**
 * The generated type map as a pure function of the routes Nitro serves. The
 * text is a function of route keys and handler paths, never of what a
 * handler declares: the compiler re-resolves every `typeof import(…)` on each
 * edit, and anything resolved at emit time would go stale with nothing to
 * regenerate it.
 */

/** The specifier every block of the map augments: this package's own `/types`. */
const TYPES_SPECIFIER = '@dphonys/better-handler/types'

const GENERATED_BY = '@dphonys/better-handler'

// Escaping, not rejection: a route key is a file name and must reach the map
// verbatim or it stops matching Nitro's.
const STRING_ESCAPES = new Map([
  ['\\', '\\\\'],
  ["'", "\\'"],
  ['\n', '\\n'],
  ['\r', '\\r'],
  ['\u2028', '\\u2028'],
  ['\u2029', '\\u2029'],
])

const NEEDS_ESCAPE = /[\\'\n\r\u2028\u2029]/g

/** One handler Nitro routes, as the map renderer needs it. */
export interface RouteHandler {
  /** Nitro's route key, verbatim. */
  readonly route: string
  /** Lowercased; `default` when the handler names no method. */
  readonly method: string
  /** `typeof import('<specifier>').default`, the specifier relative to the map. */
  readonly handlerType: string
}

/** One interface of the map, as data. */
export interface EmitMapSlot {
  /** The interface of `@dphonys/better-handler/types` the slot reopens. */
  readonly interfaceName: string
  /** The names the extractor uses, imported from `@dphonys/better-handler/types`. */
  readonly imports: readonly string[]
  /** Renders one handler's value from its `handlerType` text. */
  readonly extract: (handlerType: string) => string
}

/**
 * The `KnownApiErrors` slot: each handler's Known errors as they arrive on a
 * client. `Wire` also closes the door an index-signature handler would open:
 * such a handler reads as `never`, never as `unknown`.
 */
export const KNOWN_ERRORS_SLOT: EmitMapSlot = {
  interfaceName: 'KnownApiErrors',
  imports: ['KnownErrorsOfHandler', 'Wire'],
  extract: (handlerType) => `Wire<KnownErrorsOfHandler<${handlerType}>>`,
}

/**
 * The `KnownApiRequestInputs` slot: each handler's Request input, every
 * declared source as its schemas' input type. Unwrapped: the input is what a
 * client sends, so nothing is serialised, and nothing is simplified either -
 * nitropack's `Simplify` would turn a coerce input's `unknown` into `{}`,
 * refusing a `null` the schema accepts.
 */
export const REQUEST_INPUTS_SLOT: EmitMapSlot = {
  interfaceName: 'KnownApiRequestInputs',
  imports: ['RequestInputOfHandler'],
  extract: (handlerType) => `RequestInputOfHandler<${handlerType}>`,
}

/** The slots of the one generated type map the module registers. */
export const BETTER_HANDLER_MAP: readonly EmitMapSlot[] = [
  KNOWN_ERRORS_SLOT,
  REQUEST_INPUTS_SLOT,
]

/** A TypeScript string literal for `value`, single-quoted. */
export function stringLiteral(value: string): string {
  return `'${value.replaceAll(NEEDS_ESCAPE, (char) => STRING_ESCAPES.get(char) ?? char)}'`
}

/** One method of a route: its quoted key and the handler types it unions. */
type MethodRow = readonly [method: string, handlerTypes: readonly string[]]

/** One route of the grid: its quoted key, then its methods in order. */
type RouteRow = readonly [route: string, methods: readonly MethodRow[]]

/**
 * Render the generated map: one `declare module` block reopening each slot's
 * interface, every route keyed in each. Routes and methods are sorted, so the
 * output is a function of the route set; several handlers on one route and
 * method are unioned in the order given. Every route is keyed, branded or
 * not: an unbranded handler extracts to `never` on its own.
 */
export function emitMap(
  routes: readonly RouteHandler[],
  slots: readonly EmitMapSlot[]
): string {
  // A `Map` rather than an object literal: `__proto__` is a legal directory name.
  const grouped = new Map<string, Map<string, string[]>>()

  for (const { route, method, handlerType } of routes) {
    const methods = getOrCreate(grouped, route, () => new Map())

    getOrCreate(methods, method, () => []).push(handlerType)
  }

  // Sorted and escaped once; each slot only supplies the extractor.
  const grid: RouteRow[] = sortedEntries(grouped).map(([route, methods]) => [
    stringLiteral(route),
    sortedEntries(methods).map(([method, handlerTypes]) => [
      stringLiteral(method),
      handlerTypes,
    ]),
  ])

  return [
    `// Generated by ${GENERATED_BY} - do not edit`,
    ...renderImports(slots),
    `declare module ${stringLiteral(TYPES_SPECIFIER)} {`,
    ...slots.flatMap((slot) => renderSlot(slot, grid)),
    '}',
    // Makes this a module, which makes the block above an augmentation of the
    // package's interfaces rather than a fresh ambient module.
    'export {}',
    '',
  ].join('\n')
}

// One line, every slot's names merged and sorted.
function renderImports(slots: readonly EmitMapSlot[]): string[] {
  const names = new Set(slots.flatMap((slot) => slot.imports))

  if (names.size === 0) return []

  return [
    `import type { ${sorted(names).join(', ')} } from ${stringLiteral(TYPES_SPECIFIER)}`,
  ]
}

function renderSlot(slot: EmitMapSlot, grid: readonly RouteRow[]): string[] {
  return [
    `  interface ${slot.interfaceName} {`,
    ...grid.map(([route, methods]) => renderRoute(route, methods, slot)),
    '  }',
  ]
}

function renderRoute(
  route: string,
  methods: readonly MethodRow[],
  slot: EmitMapSlot
): string {
  return [
    `    ${route}: {`,
    ...methods.map(
      ([method, handlerTypes]) =>
        `      ${method}: ${handlerTypes.map(slot.extract).join(' | ')}`
    ),
    '    }',
  ].join('\n')
}

function getOrCreate<K, V>(map: Map<K, V>, key: K, create: () => V): V {
  const existing = map.get(key)
  if (existing !== undefined) return existing

  const created = create()
  map.set(key, created)

  return created
}

// Codepoint order rather than `localeCompare`: the output must be identical
// on every machine that builds the app.
function sortedEntries<V>(map: ReadonlyMap<string, V>): [string, V][] {
  return [...map].toSorted(([left], [right]) => compare(left, right))
}

function sorted(values: Iterable<string>): string[] {
  return [...values].toSorted(compare)
}

function compare(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0
}
