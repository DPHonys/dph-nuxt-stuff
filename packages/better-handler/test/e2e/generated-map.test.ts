import { execFile } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { promisify } from 'node:util'
import { beforeAll, describe, expect, it } from 'vitest'

// The generated map as a real app's `nuxt prepare` writes it: the
// only layer that catches the template's hooks silently ceasing to fire.
// `prepare` rather than a build, because `types:extend` fires inside Nitro's
// `writeTypes`, which is what `prepare` runs. The claims here are where the
// file lands and what it keys; that the text resolves, and to what, is
// `playground/known-errors.check.ts`'s and `playground/request-inputs.check.ts`'s,
// compiled by `pnpm typecheck`.

const run = promisify(execFile)

const PLAYGROUND = fileURLToPath(new URL('../../playground', import.meta.url))
const BUILT_MODULE = fileURLToPath(
  new URL('../../dist/module.mjs', import.meta.url)
)

// Written out rather than taken from the module: a test reading the path off
// the code under test would follow the file wherever it moved.
const MAP_PATH = join(PLAYGROUND, '.nuxt/types/better-handler.d.ts')

/** The `nuxt` CLI of the Nuxt this suite is installed against. */
function nuxtCli(): string {
  const manifestPath = createRequire(import.meta.url).resolve(
    'nuxt/package.json'
  )
  // SAFETY: every `nuxt` manifest this suite installs against (4.0.x and the
  // latest 4.x) maps `bin.nuxt` to its CLI.
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as {
    bin: { nuxt: string }
  }
  return join(dirname(manifestPath), manifest.bin.nuxt)
}

let map: string

beforeAll(async () => {
  if (!existsSync(BUILT_MODULE)) {
    throw new Error(
      'No `dist` to install from. Run `pnpm run build` in this package, or ' +
        'run the suite through `turbo run test`, which builds it first.'
    )
  }

  await run(process.execPath, [nuxtCli(), 'prepare', PLAYGROUND], {
    cwd: PLAYGROUND,
  })

  if (!existsSync(MAP_PATH)) {
    throw new Error(
      '`nuxt prepare` wrote no map to `.nuxt/types/better-handler.d.ts`: the ' +
        "template was never registered, or landed outside Nitro's types " +
        'directory, where every specifier in it resolves to nothing.'
    )
  }

  map = readFileSync(MAP_PATH, 'utf8')
})

describe('the generated map, in a real app', () => {
  it('lands in Nitro’s types directory, written by this package', () => {
    expect(map.split('\n')[0]).toBe(
      '// Generated by @dphonys/better-handler - do not edit'
    )
  })

  it('keys every route the app serves, as Nitro keys them', () => {
    // Nitro's own `[id]` to `:id` rewrite, and its extension stripping.
    expect(map).toContain(`    '/api/orders/:id': {`)
    expect(map).toContain(
      `      'get': Wire<KnownErrorsOfHandler<typeof import('../../server/api/orders/[id].get').default>>`
    )
    expect(map).toContain(`    '/api/effect': {`)
  })

  it('carries every route’s Request input beside its Known errors', () => {
    expect(map).toContain('  interface KnownApiRequestInputs {')
    expect(map).toContain(
      `      'post': RequestInputOfHandler<typeof import('../../server/api/users.post').default>`
    )
  })

  it('augments the package’s own types entry and names no Nitro specifier', () => {
    expect(map).toContain(`declare module '@dphonys/better-handler/types' {`)
    expect(map).not.toContain('nitropack')
    expect(map.trimEnd().endsWith('export {}')).toBe(true)
  })

  it.each([
    ['the app', '.nuxt/nuxt.d.ts'],
    ['shared code', '.nuxt/nuxt.shared.d.ts'],
    ['the server', '.nuxt/types/nitro-nuxt.d.ts'],
  ])('is referenced from %s', (_, file) => {
    // Each is the `addTypeTemplate` context flag it is named for; passing a
    // context at all opts out of every one it leaves out.
    expect(readFileSync(join(PLAYGROUND, file), 'utf8')).toContain(
      'better-handler.d.ts'
    )
  })

  it('is not hoisted: no generated tsconfig maps the types entry by hand', () => {
    // The package's `exports` resolves it; `generated-tsconfigs.test.ts`
    // proves that resolution under every generated tsconfig.
    for (const tsconfig of ['tsconfig.json', 'tsconfig.server.json']) {
      expect(
        readFileSync(join(PLAYGROUND, '.nuxt', tsconfig), 'utf8')
      ).not.toContain('"@dphonys/better-handler/types"')
    }
  })
})
