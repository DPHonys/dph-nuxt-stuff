import { describe, expect, it } from 'vitest'
import { emitMap, KNOWN_ERRORS_SLOT } from '../../src/build/emit-map'
import type { EmitMapSlot, RouteHandler } from '../../src/build/emit-map'

// The renderer as a pure function: string comparisons only. Whether the text
// resolves is `test/types/emitted-map.test.ts`'s job, which compiles it: an
// unresolved `import('…')` in a `.d.ts` produces no diagnostic and collapses
// silently.

/** The `typeof import(…)` text the route discovery seam hands over. */
function handlerType(specifier: string): string {
  return `typeof import('${specifier}').default`
}

function route(path: string, method: string, specifier: string): RouteHandler {
  return { route: path, method, handlerType: handlerType(specifier) }
}

/** The `'<method>': …` line one route and method renders as. */
function entryLine(method: string, ...specifiers: string[]): string {
  const values = specifiers.map(
    (specifier) => `Wire<KnownErrorsOfHandler<${handlerType(specifier)}>>`
  )

  return `      '${method}': ${values.join(' | ')}`
}

const ORDER = route(
  '/api/orders/:id',
  'get',
  '../../server/api/orders/[id].get'
)

describe('the generated map’s frame', () => {
  const emitted = emitMap([ORDER], [KNOWN_ERRORS_SLOT])

  it('renders as a whole, readable declaration', () => {
    expect(emitted).toBe(
      [
        '// Generated by @dphonys/better-handler - do not edit',
        `import type { KnownErrorsOfHandler, Wire } from '@dphonys/better-handler/types'`,
        `declare module '@dphonys/better-handler/types' {`,
        '  interface KnownApiErrors {',
        `    '/api/orders/:id': {`,
        entryLine('get', '../../server/api/orders/[id].get'),
        '    }',
        '  }',
        '}',
        'export {}',
        '',
      ].join('\n')
    )
  })

  it('augments the package’s own specifier and names no Nitro one', () => {
    expect(emitted).toContain(
      `declare module '@dphonys/better-handler/types' {`
    )
    expect(emitted).not.toContain('nitropack')
  })

  it('ends in an empty export, so the file is a module', () => {
    // Without it the file is ambient, and the block above declares a fresh
    // module instead of augmenting the package's.
    expect(emitted.trimEnd().endsWith('export {}')).toBe(true)
  })

  it('renders an empty interface for no routes, in the same file shell', () => {
    expect(emitMap([], [KNOWN_ERRORS_SLOT])).toBe(
      [
        '// Generated by @dphonys/better-handler - do not edit',
        `import type { KnownErrorsOfHandler, Wire } from '@dphonys/better-handler/types'`,
        `declare module '@dphonys/better-handler/types' {`,
        '  interface KnownApiErrors {',
        '  }',
        '}',
        'export {}',
        '',
      ].join('\n')
    )
  })
})

describe('routes and methods', () => {
  it('keeps a route’s methods apart, a default beside them', () => {
    const emitted = emitMap(
      [
        route('/api/y', 'default', '../../server/api/y'),
        route('/api/y', 'post', '../../server/api/y.post'),
      ],
      [KNOWN_ERRORS_SLOT]
    )

    expect(emitted).toContain(
      [
        `    '/api/y': {`,
        entryLine('default', '../../server/api/y'),
        entryLine('post', '../../server/api/y.post'),
        '    }',
      ].join('\n')
    )
  })

  it('unions several handlers on one route and method, in the order given', () => {
    const emitted = emitMap(
      [
        route('/api/dup', 'get', '../../server/api/dup.get'),
        route('/api/dup', 'get', '../../modules/extra/dup.get'),
      ],
      [KNOWN_ERRORS_SLOT]
    )

    expect(emitted).toContain(
      entryLine(
        'get',
        '../../server/api/dup.get',
        '../../modules/extra/dup.get'
      )
    )
  })

  it('is a function of the route set, not of the order it arrived in', () => {
    const a = route('/api/a', 'get', '../../server/api/a.get')
    const b = route('/api/b', 'post', '../../server/api/b.post')
    const bGet = route('/api/b', 'get', '../../server/api/b.get')

    expect(emitMap([a, b, bGet], [KNOWN_ERRORS_SLOT])).toBe(
      emitMap([bGet, b, a], [KNOWN_ERRORS_SLOT])
    )
  })

  it('sorts by code point, the same on every machine', () => {
    const emitted = emitMap(
      [
        route('/api/b', 'get', './b'),
        route('/api/B', 'get', './B'),
        route('/api/a', 'get', './a'),
      ],
      [KNOWN_ERRORS_SLOT]
    )

    const keys = emitted
      .split('\n')
      .filter((line) => /^ {4}'/.test(line))
      .map((line) => line.trim())

    expect(keys).toEqual([`'/api/B': {`, `'/api/a': {`, `'/api/b': {`])
  })

  it('keys a route named like an object’s own property', () => {
    // A directory may be called `__proto__`; an object literal would lose it.
    const emitted = emitMap(
      [route('/__proto__', 'get', './proto.get')],
      [KNOWN_ERRORS_SLOT]
    )

    expect(emitted).toContain(`    '/__proto__': {`)
  })
})

describe('string literals', () => {
  it('escapes a quote and a backslash rather than emitting broken TypeScript', () => {
    expect(
      emitMap([route(`/it's\\here`, 'get', './x')], [KNOWN_ERRORS_SLOT])
    ).toContain(`    '/it\\'s\\\\here': {`)
  })

  it('escapes every line terminator, which would leave the literal unterminated', () => {
    const terminators = [
      '\n',
      '\r',
      String.fromCharCode(0x2028),
      String.fromCharCode(0x2029),
    ]
    const emitted = emitMap(
      terminators.map((terminator) => route(`/a${terminator}b`, 'get', './x')),
      [KNOWN_ERRORS_SLOT]
    )

    for (const escaped of ['\\n', '\\r', '\\u2028', '\\u2029']) {
      expect(emitted).toContain(`    '/a${escaped}b': {`)
    }

    // Every literal opened on a route line closes on it.
    expect(
      emitted.split('\n').filter((line) => /^ {4}'/.test(line))
    ).toHaveLength(4)
    expect(emitted).not.toMatch(/[\r\u2028\u2029]/)
  })
})

describe('slots', () => {
  /** A second interface, as the request-inputs slot will add. */
  const SECOND: EmitMapSlot = {
    interfaceName: 'KnownApiRequestInputs',
    imports: ['Wire', 'RequestInputOfHandler'],
    extract: (type) => `RequestInputOfHandler<${type}>`,
  }

  it('reopens each slot’s interface in turn, inside the one block', () => {
    expect(emitMap([ORDER], [KNOWN_ERRORS_SLOT, SECOND])).toBe(
      [
        '// Generated by @dphonys/better-handler - do not edit',
        `import type { KnownErrorsOfHandler, RequestInputOfHandler, Wire } from '@dphonys/better-handler/types'`,
        `declare module '@dphonys/better-handler/types' {`,
        '  interface KnownApiErrors {',
        `    '/api/orders/:id': {`,
        entryLine('get', '../../server/api/orders/[id].get'),
        '    }',
        '  }',
        '  interface KnownApiRequestInputs {',
        `    '/api/orders/:id': {`,
        `      'get': RequestInputOfHandler<${handlerType('../../server/api/orders/[id].get')}>`,
        '    }',
        '  }',
        '}',
        'export {}',
        '',
      ].join('\n')
    )
  })

  it('names what the map renders and nothing about what a route declares', () => {
    // The map is a function of routes and paths; anything resolved from a
    // declaration at emit time would go stale with nothing to regenerate it.
    const emitted = emitMap([ORDER], [KNOWN_ERRORS_SLOT])

    expect(emitted).not.toContain('_tag')
    expect(emitted).not.toContain('status')
  })
})
